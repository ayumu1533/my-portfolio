int insert_bt(struct node* nodep, struct node** ptr, int key) {
	int i;
	if (nodep == 0) {//nodepが空の時
		*ptr = create_node(0, key, 0);
		return 0;
	}
	else if (key == nodep->value) {//追加できないとき
		return -1;
	}
	else if (key < nodep->value) {//現在の値のより左にkeyがあるとき
		ptr = &(nodep->left);
		i = insert_bt(nodep->left, ptr, key);
	}
	else {//現在の値のより右にkeyがあるとき
		ptr = &(nodep->right);
		i = insert_bt(nodep->right, ptr, key);
	}
	if (i == -1) {//追加しないとき
		return -1;
	}
	else {//深さを返すとき
		return i + 1;
	}
}
