/*
create_node：木の節点を1つ作る関数
引数left,value,right：左の子の節点へのポインタをleft,現在の節点にある値をvalue,右の子の節点へのポインタをright
戻り値：作った節点へのポインタ
テスト：
引数：(0,1,0)として関数から戻ってきた構造体をmain関数内で定義したstruct node型のn1に代入する。
main関数内で節点ができているか確認するために、printf("%d %d %d",n1->value,n1->left,n1->right);とすると
出力：1 0 0　　となる。
struct node*型のn2もn1と同様に引数を(0,2,0)としてつくる。
引数：(n1,3,n2)として関数から戻ってきた構造体をmain関数内で定義したstruct node型のn3に代入する。
main関数内でその節点をprintf("%d %d %d",n3->value,n3->left,n3->right);と出力すると
出力：3 -1535999696 -1535999120
printf(%d,%d,n1,n2);として出力すると
出力：-1535999696 -1535999120
そのためn3のleftがn1へのアドレスと等しくなり、rightがn2のアドレスになっているため、左の子と右の子が他の節とつながったことがわかる。
左の子と右の子の値はprintf("%d %d",n3->left->value,n3->right->value);と出力すると
出力：	1 2
となるため、n1とn2の値が出力される。
これらの確認からこの関数は正常に動作したと判断した。
なお、メモリが確保できないことをテストするにはmallocの引数に0より小さい値を入れるか、メモリの残りのビット数が確保したいメモリのビット数
より小さい時であるため、テストできないと考えた。
*/
struct node* create_node(struct node* left, int value, struct node* right) {
	struct node* p;
	p = (struct node*)malloc(sizeof(struct node));
	if (p == 0) {
		return 0;
	}
	p->value = value;
	p->left = left;
	p->right = right;
	return p;
}
/*
print_tree：二分木を表示する関数
引数nodep：表示したい二分木の根へのポインタ
テスト：
main関数内で引数：0(根が空)とすると
出力：@  となった。
木の表現方法を<@,値,@>とする。
木が<@,1,@>の構造体を引数とすると
出力：1
これは<@,1,@>を表している。
木が<<@,1,@>,2,@>の構造体を引数とすると、
出力：<1,2,@>
木が<@,1,<@,2,@>>の構造体を引数とすると、
出力：<@,1,2>
木が<<@,1,@>,2,<@,3,@>>の構造体を引数とすると、
出力：<1,2,3>
木が<<@,1,<@,2,@>>,3,<<@,4,@>,5,@>>の構造体を引数とすると、
出力：<<@,1,2>,3,<4,5,@>>
木が<<<@,1,@>,2,<@,3,@>>,4,<<@,5,@>,6,<@,7,@>>>の構造体を引数とすると、
出力：<<1,2,3>,4,<5,6,7>>
これらの確認からこの関数は正常に動作したと判断した。
*/
void print_tree(struct node* nodep) {
	if (nodep == 0) {
		printf("@");
	}
	else if ((nodep->left == 0) && (nodep->right == 0)) {
		printf("%d", nodep->value);
	}
	else {
		printf("<");
		print_tree(nodep->left);
		printf(",");
		printf("%d", nodep->value);
		printf(",");
		print_tree(nodep->right);
		printf(">");
	}
}
/*
read_tree：ユーザーが入力した二分木を生成する関数
戻り値：生成した木の根へのアドレス
テスト：
main関数内でread_nodeの戻り値をprint_tree関数の引数として生成した木を出力する。
正しい入力の時
入力：@                            　       出力：@
入力：<1,2,3>　　　　　　     出力：<1,2,3>
誤った入力の時
入力：1,2,3>　　　　　　　   出力：「<」error
入力：<1.2,3>　　　　　　　出力：「NO.1の,」error
入力：<1,,3>　　　　　　　  出力：「値」error
入力：<1,2.3>　　　　　　　出力：「NO.2の,」error
入力：<1,2,3　　　　　　       出力：「>」error
正しく入力すると、その入力した木が正しく出力されたため、木が正常に生成されていることがわかる。
誤った入力をすると、誤った箇所のerrorが出力されることがわかる。
これらの確認からこの関数は正常に動作したと判断した。
*/
struct node* read_tree(void) {
	char a;
	int value;
	struct node* left, * right;
	scanf("%c", &a);
	if (a == '@') {//@
		return 0;
	}
	ungetc(a, stdin);
	if ((scanf("%d", &value) == 1) && (x != 0)) {//数字
		return create_node(0, value, 0);
	}
	else {
		x++;
	}
	scanf("%c", &a);
	if (a != '<') {//<
		printf("「<」error\n");
		return 0;
	}
	left = read_tree();
	scanf("%c", &a);
	if (a != ',') {//,
		printf("「NO.1の,」error\n");
		return 0;
	}
	if (scanf("%d", &value) != 1) {//数字
		printf("「値」error\n");
		return 0;
	}
	scanf("%c", &a);
	if (a != ',') {//,
		printf("「NO.2の,」error\n");
		return 0;
	}
	right = read_tree();
	scanf("%c", &a);
	if (a != '>') {//>
		printf("「>」error\n");
		return 0;
	}
	return create_node(left, value, right);
}
