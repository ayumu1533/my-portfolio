int check_bt(struct node* nodep, int min, int max) {
	int i = 1;

	if (nodep == 0) {//nodepが空の時
		return 1;
	}
	else {
		if ((nodep->value > min) && (nodep->value < max)) {
			i *= check_bt(nodep->left, min, nodep->value);//左の木の確認
			i *= check_bt(nodep->right, nodep->value, max);//右の木の確認
			return i;
		}
		else {
			return 0;
		}
	}
}
