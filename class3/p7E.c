struct node* dequeue(void) {
	if (q_head == q_tail) {//オーバーフローするとき
		printf("Queue underflow. Cannot dequeue.\n");
		return 0;
	}
	struct node * val = *q_head;//キューに格納されていた節をvalに置換
	*q_head = 0;//元の節は空にする
	q_head++;//次へ
	if (q_head == q_end) {//キューの最後に行った時
		q_head = queue;//キューの最初に戻る
	}
	return val;//戻り値は置換しておいたキューに入っていた節
}
