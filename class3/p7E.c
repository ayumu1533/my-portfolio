struct node* create_node(int x, int y, struct node* left, struct node* right, struct node* up, struct node* under, int length) {
	struct node* p;
	p = (struct node*)malloc(sizeof(struct node));
	if (p == 0) {//mallocの戻り値が0の時
		return 0;
	}
	//各メンバを代入
	p->x = x;
	p->y = y;
	p->length = length;
	p->dir[0] = up;
	p->dir[1] = right;
	p->dir[2] = under;
	p->dir[3] = left;
	return p;//新しいノードが戻り値
}
